"""Produce per-situation action tables; never pool correlated probes as scenes."""

import argparse
import csv
import json
from pathlib import Path

import numpy as np


METRICS = (
    "q1", "q2", "q_min", "actual_critic_target", "discounted_reward_return",
    "standard_soft_return", "observed_horizon", "return_tail_discount", "censored",
    "collision", "at_fault_collision", "offroad", "red_light", "goals_reached",
)


def summarize(output_dir, *, include_paired_differences=False):
    output_dir = Path(output_dir)
    rows = []
    paired_rows = []
    for probe_path in sorted((output_dir / "probes").glob("*.json")):
        probe = json.loads(probe_path.read_text())
        if probe.get("status") != "complete":
            continue
        branches = probe.get("branches", [])
        reference = {record["repeat_idx"]: record for record in branches if record["action_idx"] == 0}
        for action_idx in range(12):
            records = [record for record in branches if record["action_idx"] == action_idx]
            if not records:
                continue
            row = {"probe_id": probe_path.stem, "action_idx": action_idx, "repeats": len(records)}
            for metric in METRICS:
                values = [record.get(metric) for record in records]
                finite = np.array([value for value in values if value is not None], dtype=float)
                finite = finite[np.isfinite(finite)]
                row[f"{metric}_count"] = len(finite)
                row[f"{metric}_mean"] = float(finite.mean()) if len(finite) else None
                row[f"{metric}_sem"] = float(finite.std(ddof=1) / np.sqrt(len(finite))) if len(finite) > 1 else None
            rows.append(row)
            if not include_paired_differences:
                continue
            paired = {"probe_id": probe_path.stem, "action_idx": action_idx, "reference_action_idx": 0}
            for metric in ("q_min", "actual_critic_target", "discounted_reward_return", "standard_soft_return"):
                differences = []
                for record in records:
                    baseline = reference.get(record["repeat_idx"], {})
                    value, baseline_value = record.get(metric), baseline.get(metric)
                    if value is not None and baseline_value is not None:
                        differences.append(float(value) - float(baseline_value))
                differences = np.asarray(differences, dtype=float)
                differences = differences[np.isfinite(differences)]
                paired[f"{metric}_paired_count"] = len(differences)
                paired[f"{metric}_difference_mean"] = float(differences.mean()) if len(differences) else None
                paired[f"{metric}_difference_sem"] = (
                    float(differences.std(ddof=1) / np.sqrt(len(differences))) if len(differences) > 1 else None
                )
            paired_rows.append(paired)
    for filename, table in (("action_summary.csv", rows), ("paired_action_differences.csv", paired_rows)):
        if not table:
            continue
        destination = output_dir / filename
        with destination.open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(table[0]))
            writer.writeheader()
            writer.writerows(table)
    note = (
        "# Action comparison tables\n\n"
        f"Completed probe situations: {len({row['probe_id'] for row in rows})}. "
        f"Action rows: {len(rows)}.\n\n"
        "`action_summary.csv` gives per-situation action means, standard errors across "
        "continuation seeds, and finite-value counts. Boolean means are event frequencies. "
        "Paired action differences are not generated by default.\n\n"
        "Returns are observed suffix sums: inspect censoring, horizon and retained discount. "
        "A target-derived bootstrap is not Monte Carlo truth. Do not interpret partial-return "
        "rankings as validated infinite-horizon Q rankings, or treat agents/times in a scene "
        "as independent scene samples. With eight repeats, uncertainty and rare-event rates "
        "are preliminary. PQL targets preserve the implemented endpoint-soft recurrence.\n"
    )
    (output_dir / "ACTION_TABLES.md").write_text(note)
    return {"probe_count": len({row["probe_id"] for row in rows}), "action_rows": len(rows)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--include-paired-differences", action="store_true",
                        help="Also compare actions against action 0 using matched continuation seeds")
    arguments = parser.parse_args()
    print(json.dumps(summarize(arguments.output, include_paired_differences=arguments.include_paired_differences)))
